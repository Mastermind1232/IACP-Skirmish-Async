#!/usr/bin/env node
/**
 * Scaffold `docs/dc-cc-ledger.json` from the canonical ability-library and
 * card-effects sources. Every ability-library entry becomes one atom whose
 * owner card(s) are reverse-looked-up from dc-effects.json / cc-effects.json.
 *
 * Output shape mirrors `crr-ledger.json`:
 *   {
 *     "_meta": { generatedAt, sourceCounts },
 *     "atoms": [ { id, type, abilityKey, label, description, owners, status,
 *                  wiredSelfClaim, evidence?, reviewedBy?, notes? } ]
 *   }
 *
 * On re-run, existing atom metadata (status, evidence, reviewedBy, notes) is
 * preserved — only the structural fields (owners, label, description,
 * wiredSelfClaim) are refreshed from the source-of-truth data. This means a
 * reviewer can iterate on the ledger without losing hand-entered evidence.
 *
 * Usage:  node scripts/dc-cc-ledger-scaffold.js
 *         (overwrites docs/dc-cc-ledger.json in place)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const LIB_PATH = resolve(ROOT, 'data/ability-library.json');
const DC_PATH = resolve(ROOT, 'data/dc-effects.json');
const CC_PATH = resolve(ROOT, 'data/cc-effects.json');
const OUT_PATH = resolve(ROOT, 'docs/dc-cc-ledger.json');

const library = JSON.parse(readFileSync(LIB_PATH, 'utf8')).abilities;
const dcCards = JSON.parse(readFileSync(DC_PATH, 'utf8')).cards;
const ccCards = JSON.parse(readFileSync(CC_PATH, 'utf8')).cards;

// Preserve prior hand-entered metadata if the ledger already exists.
const prior = existsSync(OUT_PATH)
  ? JSON.parse(readFileSync(OUT_PATH, 'utf8'))
  : { atoms: [] };
const priorById = new Map((prior.atoms || []).map((a) => [a.id, a]));

function makeAtomId(type, key) {
  const prefix = { dcSpecial: 'DC-SPEC', dcPassive: 'DC-PASS', surge: 'SURGE', ccEffect: 'CC' }[type] || 'ABL';
  const slug = String(key).toUpperCase().replace(/[^A-Z0-9]+/g, '-').replace(/^-|-$/g, '');
  return `${prefix}-${slug}`;
}

// Reverse lookup: ability-library key → list of owner DCs / CCs.
const ownersByKey = new Map();
for (const [dcName, dc] of Object.entries(dcCards)) {
  for (const id of dc.specialAbilityIds || []) {
    const list = ownersByKey.get(id) || [];
    list.push({ kind: 'dc', name: dcName });
    ownersByKey.set(id, list);
  }
  for (const surgeKey of dc.surgeAbilities || []) {
    const list = ownersByKey.get(surgeKey) || [];
    list.push({ kind: 'dc-surge', name: dcName });
    ownersByKey.set(surgeKey, list);
  }
}
// CC library keys can be either (a) the CC name itself, or (b) a `cc:`-prefixed
// slug referenced via the card's `abilityId` field.
for (const [ccName, card] of Object.entries(ccCards)) {
  if (library[ccName]) {
    const list = ownersByKey.get(ccName) || [];
    list.push({ kind: 'cc', name: ccName });
    ownersByKey.set(ccName, list);
  }
  const aid = card.abilityId;
  if (aid && library[aid]) {
    const list = ownersByKey.get(aid) || [];
    list.push({ kind: 'cc', name: ccName });
    ownersByKey.set(aid, list);
  }
}

const atoms = [];
for (const [key, entry] of Object.entries(library)) {
  const type = entry.type || 'unknown';
  const id = makeAtomId(type, key);
  const owners = ownersByKey.get(key) || [];
  const base = {
    id,
    type,
    abilityKey: key,
    label: entry.label || null,
    description: entry.description || null,
    owners,
    wiredSelfClaim: entry.wiredStatus || null,
    status: 'pending',
  };
  // Preserve prior review metadata if atom existed before.
  const p = priorById.get(id);
  if (p) {
    base.status = p.status || base.status;
    if (p.evidence) base.evidence = p.evidence;
    if (p.reviewedBy) base.reviewedBy = p.reviewedBy;
    if (p.notes) base.notes = p.notes;
    if (p.implementationArea) base.implementationArea = p.implementationArea;
    if (p.exemptReason) base.exemptReason = p.exemptReason;
    if (p.implHint) base.implHint = p.implHint;
  }
  atoms.push(base);
}

// Stable sort by id for deterministic diffs.
atoms.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

const sourceCounts = {
  libraryEntries: Object.keys(library).length,
  dcCards: Object.keys(dcCards).length,
  ccCards: Object.keys(ccCards).length,
  atomsByType: atoms.reduce((acc, a) => {
    acc[a.type] = (acc[a.type] || 0) + 1;
    return acc;
  }, {}),
  atomsByStatus: atoms.reduce((acc, a) => {
    acc[a.status] = (acc[a.status] || 0) + 1;
    return acc;
  }, {}),
};

const out = {
  _meta: {
    description: 'DC/CC ledger: one atom per ability-library entry. Tracks coverage state per printed card ability. Generated by scripts/dc-cc-ledger-scaffold.js — re-run preserves hand-entered review metadata.',
    generatedAt: new Date().toISOString(),
    sourceCounts,
  },
  atoms,
};

writeFileSync(OUT_PATH, JSON.stringify(out, null, 2) + '\n');
console.log(`[dc-cc-ledger-scaffold] wrote ${atoms.length} atoms to ${OUT_PATH}`);
console.log('  by type:  ', sourceCounts.atomsByType);
console.log('  by status:', sourceCounts.atomsByStatus);
